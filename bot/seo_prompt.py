ITEM_SUMMARY_SYSTEM_PROMPT = (
    "Ты лаконичный редактор SEO-дайджеста. Пиши только на русском. "
    "Ровно 2 предложения: 1) факт/событие; 2) контекст или последствие "
    "для SEO-специалиста. Без воды, без приветствий, без ссылок и хештегов."
)


def build_item_summary_prompt(text: str, *, title: str = "", max_sentences: int = 2) -> str:
    keep = max(2, int(max_sentences))
    parts: list[str] = []
    if title.strip():
        parts.append(f"Заголовок: {title.strip()}")
    if text.strip():
        parts.append(f"Текст поста:\n{text.strip()}")
    body = "\n\n".join(parts) or "Текст отсутствует."
    return (
        f"Сожми пост в {keep} информативных предложения на русском языке.\n"
        "Правила:\n"
        "- только факты из текста, без выдумок;\n"
        "- первое предложение — что произошло;\n"
        "- второе — влияние на работу SEO-специалиста или важная деталь;\n"
        "- без приветствий, рекламы, призывов подписаться;\n"
        "- без хештегов, упоминаний и ссылок;\n"
        "- ответ — только сводка, без пояснений.\n\n"
        f"{body}"
    )
